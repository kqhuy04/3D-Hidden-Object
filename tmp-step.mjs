import fs from 'node:fs';
import { launch, waitForGame } from './tools/cdp.mjs';
const log = (s) => fs.appendFileSync('tmp-step.log', s + '\n');
fs.writeFileSync('tmp-step.log', '');
log('imported');
const cdp = await launch({ url: 'http://localhost:1420/?debug=1', port: 9496, width: 1280, height: 800 });
log('launched');
await waitForGame(cdp);
log('game ready');
const vp = await cdp.evaluate('({ VW: window.innerWidth, VH: window.innerHeight })');
log('viewport ' + JSON.stringify(vp));
await cdp.close();
log('closed');
